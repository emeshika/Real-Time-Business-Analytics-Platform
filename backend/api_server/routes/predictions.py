from fastapi import APIRouter, Query
from datetime import datetime, timedelta, timezone
import json
import os

from api_server.db import get_predictions_col, get_hourly_col, serialise_doc
from analytics_ml.metrics import (
    mean_absolute_error,
    root_mean_squared_error,
    mean_absolute_percentage_error,
)

log = logging.getLogger("pulsebi.predictions")

router = APIRouter(prefix="/api/predictions", tags=["ML Predictions"])


def _parse_datetime(value):
    if isinstance(value, datetime):
        return value.astimezone(timezone.utc)
    if not value:
        return None
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00")).astimezone(timezone.utc)
    except ValueError:
        return None


def _target_hour(prediction):
    target = _parse_datetime(prediction.get("target_hour"))
    if target:
        return target.replace(minute=0, second=0, microsecond=0)
    based_on = _parse_datetime(prediction.get("based_on_latest_hour"))
    if based_on:
        return (based_on + timedelta(hours=1)).replace(minute=0, second=0, microsecond=0)
    prediction_time = _parse_datetime(prediction.get("prediction_time"))
    if prediction_time:
        return (prediction_time + timedelta(hours=1)).replace(minute=0, second=0, microsecond=0)
    return None


@router.get("/evaluation")
def get_prediction_evaluation(limit: int = Query(default=200, ge=1, le=1000)):
    """Return offline, backtest, and stream metrics without mixing sources."""
    metrics_path = os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
        "analytics_ml", "models", "metrics.json",
    )
    try:
        with open(metrics_path, "r", encoding="utf-8") as metrics_file:
            saved_metrics = json.load(metrics_file)
    except (FileNotFoundError, json.JSONDecodeError):
        saved_metrics = None

    now = datetime.now(timezone.utc)

    def evaluate_source(source):
        predictions = [
            serialise_doc(dict(doc))
            for doc in get_predictions_col()
            .find({"source": source}, {"_id": 0})
            .sort("target_hour", -1)
            .limit(limit)
        ]
        model_actual = []
        model_predicted = []
        naive_actual = []
        naive_predicted = []
        mean24_actual = []
        mean24_predicted = []
        evaluated = []

        for prediction in predictions:
            target = _target_hour(prediction)
            if not target or target >= now.replace(minute=0, second=0, microsecond=0):
                continue
            actual_doc = get_hourly_col().find_one({"hour_start": target})
            if not actual_doc:
                continue

            actual = float(actual_doc.get("total_cost", 0.0) or 0.0)
            predicted = float(prediction.get("predicted_total_cost_next_hour", 0.0) or 0.0)
            previous = get_hourly_col().find_one({"hour_start": target - timedelta(hours=1)})
            naive = float(previous.get("total_cost", 0.0) or 0.0) if previous else None

            model_actual.append(actual)
            model_predicted.append(predicted)
            if naive is not None:
                naive_actual.append(actual)
                naive_predicted.append(naive)
            previous_docs = list(
                get_hourly_col()
                .find({"hour_start": {"$lt": target}})
                .sort("hour_start", -1)
                .limit(24)
            )
            previous_costs = [
                float(doc.get("total_cost", 0.0) or 0.0)
                for doc in previous_docs
            ]
            mean24 = sum(previous_costs) / len(previous_costs) if previous_costs else None
            if mean24 is not None:
                mean24_actual.append(actual)
                mean24_predicted.append(mean24)
            evaluated.append({
                "target_hour": target.isoformat().replace("+00:00", "Z"),
                "actual_revenue": actual,
                "model_predicted": predicted,
                "naive_predicted": naive,
                "mean24_predicted": mean24,
            })

        n = len(evaluated)
        return {
            "source": source,
            "n": n,
            "label": "n=%d, too few to conclude" % n if n < 20 else "n=%d" % n,
            "model": {
                "mae": mean_absolute_error(model_actual, model_predicted),
                "rmse": root_mean_squared_error(model_actual, model_predicted),
                "mape": mean_absolute_percentage_error(model_actual, model_predicted),
            },
            "naive_baseline": {
                "mae": mean_absolute_error(naive_actual, naive_predicted),
                "rmse": root_mean_squared_error(naive_actual, naive_predicted),
                "mape": mean_absolute_percentage_error(naive_actual, naive_predicted),
            },
            "mean_24h": {
                "mae": mean_absolute_error(mean24_actual, mean24_predicted),
                "rmse": root_mean_squared_error(mean24_actual, mean24_predicted),
                "mape": mean_absolute_percentage_error(mean24_actual, mean24_predicted),
            },
            "evaluated": evaluated,
        }

    return {
        "offline_test": saved_metrics,
        "backtest": evaluate_source("backtest"),
        "stream": evaluate_source("stream"),
    }

# ── GET /api/predictions ──────────────────────────────────────────────────────


@router.get("/")
def get_predictions(
    limit: int = Query(default=10, ge=1, le=200, description="Max predictions to return"),
):
    """
    Fetch the most recent ML prediction documents.

    Returns JSON::

        { "predictions": [ {...}, ... ], "count": 10 }
    """
    cursor = (
        get_predictions_col()
        .find({}, {"_id": 0})
        .sort("created_at", -1)
        .limit(limit)
    )
    results = [serialise_doc(doc) for doc in cursor]
    log.info("Served %d prediction records", len(results))
    return {"predictions": results, "count": len(results)}


# ── GET /api/predictions/latest ───────────────────────────────────────────────


@router.get("/latest")
def get_latest_prediction():
    """
    Return the single most-recent prediction document.

    Returns JSON::

        { "prediction": {...} }
    """
    doc = get_predictions_col().find_one(
        {}, {"_id": 0}, sort=[("created_at", -1)]
    )
    result = serialise_doc(doc) if doc else None
    log.info("Served latest prediction: %s", "found" if result else "none")
    return {"prediction": result}
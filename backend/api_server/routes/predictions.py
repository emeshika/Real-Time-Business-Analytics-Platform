"""
routes/predictions.py
---------------------
REST endpoints for ML predictions generated by Team 03.

GET /api/predictions             - Recent predictions
GET /api/predictions/latest      - Most recent prediction
GET /api/predictions/evaluation  - Offline, backtest and stream metrics
                                   (never mixed, complete hours only)
"""

from __future__ import annotations

import json
import logging
import os
from datetime import datetime, timedelta, timezone

from fastapi import APIRouter, Query

from analytics_ml.metrics import (
    mean_absolute_error,
    mean_absolute_percentage_error,
    root_mean_squared_error,
)
from api_server.db import get_hourly_col, get_predictions_col, serialise_doc
from config import is_complete_hour

log = logging.getLogger("pulsebi.predictions")

router = APIRouter(prefix="/api/predictions", tags=["ML Predictions"])

MIN_MEAN24_HOURS = 12


def _to_utc(value):
    """Parse a datetime or ISO string into an aware UTC datetime.

    Naive datetimes (what PyMongo returns) are UTC, not local time.
    """
    if isinstance(value, datetime):
        if value.tzinfo is None:
            return value.replace(tzinfo=timezone.utc)
        return value.astimezone(timezone.utc)
    if not value:
        return None
    try:
        parsed = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except ValueError:
        return None
    return _to_utc(parsed)


def _floor_hour(value):
    return value.replace(minute=0, second=0, microsecond=0)


def _target_hour(prediction):
    target = _to_utc(prediction.get("target_hour"))
    if target:
        return _floor_hour(target)
    based_on = _to_utc(prediction.get("based_on_latest_hour"))
    if based_on:
        return _floor_hour(based_on + timedelta(hours=1))
    generated = _to_utc(prediction.get("prediction_time"))
    if generated:
        return _floor_hour(generated + timedelta(hours=1))
    return None


def _hourly_lookup(start, end):
    cursor = get_hourly_col().find(
        {"hour_start": {"$gte": start, "$lte": end}},
        {"_id": 0, "hour_start": 1, "total_cost": 1, "total_transactions": 1},
    )
    lookup = {}
    for doc in cursor:
        stamp = _to_utc(doc.get("hour_start"))
        if stamp:
            lookup[_floor_hour(stamp)] = doc
    return lookup


def _cost(doc):
    return float(doc.get("total_cost", 0.0) or 0.0)


def _scores(actual, predicted):
    return {
        "mae": mean_absolute_error(actual, predicted),
        "rmse": root_mean_squared_error(actual, predicted),
        "mape": mean_absolute_percentage_error(actual, predicted),
    }


def _evaluate_source(source: str, limit: int):
    predictions = [
        serialise_doc(dict(doc))
        for doc in get_predictions_col()
        .find({"source": source}, {"_id": 0})
        .sort("target_hour", -1)
        .limit(limit)
    ]

    targets = []
    for prediction in predictions:
        target = _target_hour(prediction)
        if target:
            targets.append((prediction, target))

    lookup = {}
    if targets:
        first = min(t for _, t in targets) - timedelta(hours=25)
        last = max(t for _, t in targets)
        lookup = _hourly_lookup(first, last)

    current_hour = _floor_hour(datetime.now(timezone.utc))
    model_actual, model_pred = [], []
    naive_actual, naive_pred = [], []
    mean_actual, mean_pred = [], []
    evaluated = []
    skipped_incomplete = 0

    for prediction, target in targets:
        if target >= current_hour:
            continue  # the hour has not finished yet

        actual_doc = lookup.get(target)
        if not actual_doc or not is_complete_hour(actual_doc.get("total_transactions")):
            skipped_incomplete += 1
            continue

        actual = _cost(actual_doc)
        predicted = float(prediction.get("predicted_total_cost_next_hour", 0.0) or 0.0)
        model_actual.append(actual)
        model_pred.append(predicted)

        previous = lookup.get(target - timedelta(hours=1))
        naive = None
        if previous and is_complete_hour(previous.get("total_transactions")):
            naive = _cost(previous)
            naive_actual.append(actual)
            naive_pred.append(naive)

        history = [
            _cost(lookup[target - timedelta(hours=h)])
            for h in range(1, 25)
            if (target - timedelta(hours=h)) in lookup
            and is_complete_hour(lookup[target - timedelta(hours=h)].get("total_transactions"))
        ]
        mean24 = sum(history) / len(history) if len(history) >= MIN_MEAN24_HOURS else None
        if mean24 is not None:
            mean_actual.append(actual)
            mean_pred.append(mean24)

        evaluated.append({
            "target_hour": target.isoformat().replace("+00:00", "Z"),
            "actual_revenue": actual,
            "model_predicted": predicted,
            "naive_predicted": naive,
            "mean24_predicted": mean24,
        })

    n = len(evaluated)
    return {
        "source": source,
        "n": n,
        "label": f"n={n}, too few to conclude" if n < 20 else f"n={n}",
        "skipped_incomplete": skipped_incomplete,
        "model": _scores(model_actual, model_pred),
        "naive_baseline": _scores(naive_actual, naive_pred),
        "mean_24h": _scores(mean_actual, mean_pred),
        "evaluated": evaluated,
    }


@router.get("/evaluation")
def get_prediction_evaluation(limit: int = Query(default=200, ge=1, le=1000)):
    """Offline, backtest and stream metrics, kept separate."""
    metrics_path = os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
        "analytics_ml", "models", "metrics.json",
    )
    try:
        with open(metrics_path, "r", encoding="utf-8") as metrics_file:
            saved_metrics = json.load(metrics_file)
    except (FileNotFoundError, json.JSONDecodeError):
        saved_metrics = None

    return {
        "offline_test": saved_metrics,
        "backtest": _evaluate_source("backtest", limit),
        "stream": _evaluate_source("stream", limit),
    }


@router.get("/")
def get_predictions(
    limit: int = Query(default=10, ge=1, le=200, description="Max predictions to return"),
):
    """Most recent prediction documents (newest first)."""
    cursor = (
        get_predictions_col()
        .find({}, {"_id": 0})
        .sort("created_at", -1)
        .limit(limit)
    )
    results = [serialise_doc(doc) for doc in cursor]
    log.info("Served %d prediction records", len(results))
    return {"predictions": results, "count": len(results)}


@router.get("/latest")
def get_latest_prediction():
    """The single most recent prediction document."""
    doc = get_predictions_col().find_one({}, {"_id": 0}, sort=[("created_at", -1)])
    result = serialise_doc(doc) if doc else None
    log.info("Served latest prediction: %s", "found" if result else "none")
    return {"prediction": result}
